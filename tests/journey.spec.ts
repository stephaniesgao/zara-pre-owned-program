import {test,expect} from '@playwright/test';
test('shopping, rewards, redemption and one-time referral',async({page})=>{
 await page.goto('/?demo=1');
 await page.getByRole('button',{name:'ADD',exact:true}).click();
 await page.getByRole('button',{name:'S',exact:true}).click();
 await page.getByRole('button',{name:'ADD · S',exact:true}).click();
 await page.getByRole('button',{name:'Increase quantity VELVET RUCHED MINI DRESS',exact:true}).click();
 await expect(page.getByText('$ 119.80',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Decrease quantity VELVET RUCHED MINI DRESS',exact:true}).click();
 await page.getByRole('button',{name:'CONTINUE TO DEMO CHECKOUT',exact:true}).click();
 await page.getByRole('button',{name:'CONFIRM SIMULATED PURCHASE',exact:true}).click();
 await expect(page.getByText('Your new piece is confirmed. New purchases do not earn Pre-Owned points.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Close',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:/^ZARA BLACK TEXTURED MINI DRESS WITH RHINESTONE BUTTONS.*PRE-OWNED/}).click();
 await expect(page).toHaveURL(/product=pre-0/);
 await page.getByRole('button',{name:'ADD',exact:true}).click();
 await page.getByRole('button',{name:'S',exact:true}).click();
 await page.getByRole('button',{name:'ADD · S',exact:true}).click();
 await page.getByRole('button',{name:'CONTINUE TO DEMO CHECKOUT',exact:true}).click();
 await page.getByRole('button',{name:'CONFIRM SIMULATED PURCHASE',exact:true}).click();
 await expect(page.getByText('+100 points have been added to your membership.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'VIEW MEMBERSHIP PROGRESS',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:'SILVER',exact:true}).click();
 await expect(page.locator('.tier-heading')).toContainText('300');
 await expect(page.locator('.partner:not(.locked)')).toHaveCount(6);
 await page.getByRole('button',{name:'GOLD',exact:true}).click();
 await expect(page.locator('.tier-heading')).toContainText('700');
 await expect(page.locator('.partner:not(.locked)')).toHaveCount(11);
 await page.locator('.partner').filter({has:page.getByRole('heading',{name:'UpCircle',exact:true})}).getByRole('button',{name:'Skincare credit AVAILABLE TO REDEEM 100 PTS ↗',exact:true}).click();
 await page.getByRole('button',{name:'CONFIRM DEMO REDEMPTION',exact:true}).click();
 await expect(page.getByRole('dialog')).toContainText('Spendable balance: 600 points');
 await expect(page.getByRole('dialog')).toContainText('Membership: GOLD · 700 qualifying points');
 await page.getByRole('button',{name:'RETURN TO REWARDS',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:'GENERATE DEMO LINK',exact:true}).click();
 await page.getByRole('button',{name:'SIMULATE INVITATION',exact:true}).click();
 await expect(page.locator('.tier-heading')).toContainText('700');
 await page.getByRole('button',{name:'SIMULATE FRIEND’S FIRST PURCHASE',exact:true}).click();
 await expect(page.getByRole('button',{name:'BONUS ALREADY AWARDED',exact:true})).toBeDisabled();
 await expect(page.locator('.referral')).toContainText('Friend: 150 qualifying · 150 spendable points');
 await expect(page.locator('.tier-heading')).toContainText('750');
 await page.reload();
 await expect(page.locator('.tier-heading')).toContainText('750');
 await expect(page.locator('.balance strong')).toHaveText('650');
 await page.getByRole('button',{name:'RESET ALL',exact:true}).click();
 await expect(page.getByRole('heading',{name:'VELVET RUCHED MINI DRESS',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'BAG [ 0 ]',exact:true})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('recommendations, product navigation, menu and search',async({page})=>{
 await page.goto('/?demo=1');
 await expect(page.getByRole('tab',{name:'PRE-OWNED PICKS',exact:true})).toHaveAttribute('aria-selected','true');
 await page.getByRole('button',{name:'Next recommendations',exact:true}).click();
 await page.getByRole('tab',{name:'MORE TO COMPLETE YOUR LOOK',exact:true}).click();
 await expect(page.locator('.rec-track .eyebrow').first()).toHaveText('NEW COLLECTION');
 await page.getByRole('button',{name:'Open menu',exact:true}).click();
 await page.getByRole('button',{name:'DRESSES',exact:true}).click();
 await expect(page.locator('.catalog-grid .rec-card')).toHaveCount(3);
 await page.getByRole('button',{name:'SEARCH',exact:true}).click();
 await page.getByRole('textbox',{name:'Search products',exact:true}).fill('shoulder bag');
 await expect(page.locator('.search-result')).toHaveCount(2);
 await page.getByRole('button',{name:'Close',exact:true}).click();
});
test('highlighted Pre-Owned area opens current rewards and product badge does too',async({page})=>{
 await page.goto('/?demo=1');
 await expect(page.locator('.preowned-highlight')).toContainText('0');
 await page.getByRole('button',{name:'ZARA Pre-Owned — view my rewards',exact:true}).click();
 await expect(page).toHaveURL(/view=rewards/);
 await expect(page.locator('.balance strong')).toHaveText('0');
 await page.getByRole('button',{name:'GOLD',exact:true}).click();
 await page.getByRole('button',{name:'← RETURN TO SHOPPING',exact:true}).click();
 await expect(page.locator('.compact-rewards-copy')).toContainText('700');
 await page.getByRole('button',{name:'ZARA Pre-Owned — view my rewards',exact:true}).click();
 await expect(page.locator('.tier-heading')).toContainText('GOLD');
 await expect(page.locator('.balance strong')).toHaveText('700');
 await page.goto('/?demo=1#view=product&product=pre-0');
 await page.getByRole('button',{name:'PRE-OWNED · VIEW YOUR REWARDS ↗',exact:true}).click();
 await expect(page).toHaveURL(/view=rewards/);
 await expect(page.locator('.balance strong')).toHaveText('700');
});
